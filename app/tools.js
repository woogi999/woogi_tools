// Subsequence match: every query char must appear in order. Higher is better,
// -1 means no match. Rewards consecutive runs, word starts and short targets.
export function fuzzyScore(query, text) {
  const q = query.toLowerCase();
  const t = text.toLowerCase();
  if (!q) return 0;
  let score = 0;
  let run = 0;
  let from = 0;
  for (const ch of q) {
    const i = t.indexOf(ch, from);
    if (i === -1) return -1;
    run = i === from ? run + 1 : 0;
    score += 1 + run * 2 + (i === 0 || /[\s\-_]/.test(t[i - 1]) ? 3 : 0);
    from = i + 1;
  }
  return score - t.length * 0.05;
}

export function searchTools(query) {
  const q = query.trim();
  if (!q) return TOOLS;
  return TOOLS.map((tool) => {
    const fields = [tool.label, tool.category, ...(tool.keywords ?? [])].filter(
      Boolean,
    );
    const description = tool.description?.toLowerCase() ?? '';
    // Every word must hit: fuzzy on short fields (label weighted), plain substring on the description.
    const score = q.split(/\s+/).reduce((sum, word) => {
      if (sum < 0) return sum;
      const fuzzy = Math.max(
        ...fields.map((f, i) => fuzzyScore(word, f) * (i === 0 ? 1.5 : 1)),
      );
      const best = Math.max(
        fuzzy,
        description.includes(word.toLowerCase()) ? 2 : -1,
      );
      return best < 0 ? -1 : sum + best;
    }, 0);
    return { tool, score };
  })
    .filter((r) => r.score >= 0)
    .sort((a, b) => b.score - a.score)
    .map((r) => r.tool);
}

